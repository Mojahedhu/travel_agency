import { type ActionFunctionArgs, data as res } from "react-router";
import { GoogleGenAI } from "@google/genai";

import { appwriteConfig } from "../../appwrite/client";
import { ID, Query } from "appwrite";
import { createSessionClient } from "../../appwrite/server";
import { CreateTripRequestSchema } from "../../lib/validations/trip";

import { createProduct } from "../../lib/stripe";

const { databaseId, tripCollectionId, userCollectionId } = appwriteConfig;

export const action = async ({ request }: ActionFunctionArgs) => {
  // 1. Verify User on the Server
  const { user, database } = await createSessionClient(request);
  if (!user || !database) {
    return res(
      { error: "Unauthorized: You must be logged in to create a trip." },
      { status: 401 },
    );
  }

  // 2. Verify Admin Role / Status (Forbidden if not admin)

  const { rows, total } = await database.listRows({
    databaseId,
    tableId: userCollectionId,
    queries: [Query.equal("accountId", user.$id), Query.limit(1)],
  });
  const userDoc = total > 0 ? (rows[0] as unknown as UserData) : null;
  if (userDoc?.status !== "admin") {
    return res(
      { error: "Forbidden: You do not have permission to generate trips." },
      { status: 403 },
    );
  }

  let rawBody: unknown;
  try {
    rawBody = await request.json();
  } catch {
    return res(
      {
        error: "Request body must be valid JSON.",
        issues: [
          { field: "form", message: "Request body must be valid JSON." },
        ],
      },
      { status: 400 },
    );
  }

  // 1. Safe parsing with Zod
  const validationResult = CreateTripRequestSchema.safeParse(rawBody);

  if (!validationResult.success) {
    const issues = validationResult.error.issues.map((issue) => ({
      field: issue.path.join(".") || "form",
      message: issue.message,
    }));
    return res(
      {
        error: issues[0]?.message || "Validation Error",
        issues,
      },
      { status: 400 },
    );
  }

  // 2. Type-safe validated data
  const { country, numberOfDays, travelStyle, interests, budget, groupType } =
    validationResult.data;

  // 3. Now safely use user.$id from the verified server session!
  const verifiedUserId = user.$id;

  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY! });
  const unsplashApiKey = process.env.UNSPLASH_ACCESS_KEY!;

  try {
    const prompt = `Generate a ${numberOfDays}-day travel itinerary for ${country} based on the following user information:
        Budget: '${budget}'
        Interests: '${interests}'
        TravelStyle: '${travelStyle}'
        GroupType: '${groupType}'
        Return the itinerary and lowest estimated price in a clean, non-markdown JSON format with the following structure:
        {
        "name": "A descriptive title for the trip",
        "description": "A brief description of the trip and its highlights not exceeding 100 words",
        "estimatedPrice": "Lowest average price for the trip in USD, e.g.$price",
        "duration": ${numberOfDays},
        "budget": "${budget}",
        "travelStyle": "${travelStyle}",
        "country": "${country}",
        "interests": "${interests}",
        "groupType": "${groupType}",
        "bestTimeToVisit": [
          '🌸 Season (from month to month): reason to visit',
          '☀️ Season (from month to month): reason to visit',
          '🍁 Season (from month to month): reason to visit',
          '❄️ Season (from month to month): reason to visit'
        ],
        "weatherInfo": [
          '☀️ Season: temperature range in Celsius (temperature range in Fahrenheit)',
          '🌦️ Season: temperature range in Celsius (temperature range in Fahrenheit)',
          '🌧️ Season: temperature range in Celsius (temperature range in Fahrenheit)',
          '❄️ Season: temperature range in Celsius (temperature range in Fahrenheit)'
        ],
        "location": {
          "city": "name of the city or region",
          "coordinates": [latitude, longitude],
          "openStreetMap": "link to open street map"
        },
        "itinerary": [
        {
          "day": 1,
          "location": "City/Region Name",
          "activities": [
            {"time": "Morning", "description": "🏰 Visit the local historic castle and enjoy a scenic walk"},
            {"time": "Afternoon", "description": "🖼️ Explore a famous art museum with a guided tour"},
            {"time": "Evening", "description": "🍷 Dine at a rooftop restaurant with local wine"}
          ]
        },
        ...
        ]
    }`;

    const textResult = await ai.models.generateContent({
      model: "gemini-3.5-flash-lite",
      contents: prompt,
      config: {
        responseMimeType: "application/json",
      },
    });

    const trip = JSON.parse(textResult.text);

    if (!trip || typeof trip.estimatedPrice !== "string") {
      return res(
        {
          error: "Invalid trip data generated by AI: missing estimated price.",
        },
        { status: 500 },
      );
    }

    const cleanedPrice = trip.estimatedPrice
      .replace(/,/g, "")
      .replace(/[^0-9.]/g, "");

    const tripPrice = Math.round(parseFloat(cleanedPrice) * 100) / 100;
    if (Number.isNaN(tripPrice) || tripPrice <= 0) {
      return res(
        { error: "Invalid estimated price generated for trip." },
        { status: 500 },
      );
    }

    const imageResponse = await fetch(
      `https://api.unsplash.com/search/photos?query=${encodeURIComponent(`${country} ${interests} ${travelStyle}`)}&client_id=${unsplashApiKey}`,
    );

    if (!imageResponse.ok) {
      throw new Error(
        `Failed to fetch images from Unsplash: ${imageResponse.status} ${imageResponse.statusText}`,
      );
    }

    const data = await imageResponse.json();

    const imageUrls = (data.results || [])
      .slice(0, 3)
      .map((result: any) => result.urls?.regular || null);

    const result = await database.createRow({
      databaseId,
      tableId: tripCollectionId,
      rowId: ID.unique(),
      data: {
        tripDetails: JSON.stringify(trip),
        imageUrls,
        userId: verifiedUserId,
      },
    });

    const tripDetails = trip as Trip;

    let paymentLink;

    try {
      paymentLink = await createProduct(
        tripDetails.name,
        tripDetails.description,
        imageUrls,
        tripPrice,
        result.$id,
      );

      await database.updateRow({
        databaseId,
        tableId: tripCollectionId,
        rowId: result.$id,
        data: {
          payment_link: paymentLink.url,
        },
      });
    } catch (error) {
      // Rollback / cleanup: delete orphan row if Stripe product creation or DB update fails
      // await database.deleteRow({
      //   databaseId,
      //   tableId: tripCollectionId,
      //   rowId: result.$id,
      // });
      throw error;
    }

    return res({ id: result.$id });
  } catch (e) {
    console.error("Error generating travel plan: ", e);
    return res({ error: "Internal server error" }, { status: 500 });
  }
};
